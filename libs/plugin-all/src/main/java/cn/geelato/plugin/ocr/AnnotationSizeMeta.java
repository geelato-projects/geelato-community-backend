package cn.geelato.plugin.ocr;

/**
 * PDF 注释尺寸元数据。
 *
 * @author geelato
 */
public class AnnotationSizeMeta {

    private float width;
    private float height;

    public float getWidth() {
        return width;
    }

    public void setWidth(float width) {
        this.width = width;
    }

    public float getHeight() {
        return height;
    }

    public void setHeight(float height) {
        this.height = height;
    }
}
